#!/usr/bin/env node
/**
 * @fileoverview Maintainer CLI for deterministic runtime artifact generation.
 */

import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  checkRuntimeDataFreshness,
  generateRuntimeData,
  readCrossVersionSource,
} from './runtime-data-generator.js';

const TOOL_DIR = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(TOOL_DIR, '..');

/**
 * Print CLI usage.
 *
 * @returns {void}
 */
function printUsage() {
  console.log(`Usage: node tools/build-runtime-data.js --output DIR [options]

Build all eight FML mapping artifacts and five FHIR table artifacts in a
complete candidate directory, validate them, then publish the directory.

The default FHIR definitions root is an ignored maintainer intermediate.
Generate it first with: npm run build:fhir-defs

Options:
  --output DIR          Required artifact output directory.
  --check-root DIR      Compare generated bytes without rewriting this root.
  --review-output DIR   Optional canonical uncompressed JSON output directory.
  --xver-root DIR       Cross-version input root.
  --xver-source-uri URI Source URL recorded for an alternate mapping snapshot.
  --xver-source-commit ID
                        Source commit recorded for an alternate snapshot.
  --xver-source-date YYYY-MM-DD
                        Snapshot date recorded for an alternate snapshot.
  --fhir-table-runtime-root DIR
                        Reuse verified FHIR tables from a complete runtime root.
  --fhir-defs-root DIR  Consolidated maintainer-intermediate table root.
  --fhir-spec-root DIR  Official FHIR specification archive root.
  --replace             Replace existing output directories after validation.
  --help                Show this help.
`);
}

/**
 * Read an option value following the current argument.
 *
 * @param {string[]} argv CLI arguments.
 * @param {number} index Current index.
 * @returns {string} Option value.
 */
function optionValue(argv, index) {
  const value = argv[index + 1];
  if (!value || value.startsWith('-')) {
    throw new Error(`${argv[index]} requires a directory value`);
  }

  return value;
}

/**
 * Parse command-line arguments.
 *
 * @param {string[]} argv CLI arguments after the script name.
 * @returns {Object} Generator options.
 */
export function parseArgs(argv) {
  const options = {
    output: null,
    checkRoot: null,
    reviewOutput: null,
    xverRoot: path.join(PROJECT_ROOT, 'data/fhir-cross-version/input'),
    xverSource: {},
    fhirTableRuntimeRoot: null,
    fhirDefsRoot: path.join(PROJECT_ROOT, 'data/fhir-defs'),
    fhirSpecRoot: path.join(PROJECT_ROOT, 'data/fhir-spec-downloads'),
    replace: false,
    help: false,
  };

  for (let index = 0; index < argv.length; index++) {
    const argument = argv[index];
    switch (argument) {
      case '--output':
        options.output = optionValue(argv, index);
        index++;
        break;
      case '--check-root':
        options.checkRoot = optionValue(argv, index);
        index++;
        break;
      case '--review-output':
        options.reviewOutput = optionValue(argv, index);
        index++;
        break;
      case '--xver-root':
        options.xverRoot = optionValue(argv, index);
        index++;
        break;
      case '--xver-source-uri':
        options.xverSource.uri = optionValue(argv, index);
        index++;
        break;
      case '--xver-source-commit':
        options.xverSource.commit = optionValue(argv, index);
        index++;
        break;
      case '--xver-source-date':
        options.xverSource.date = optionValue(argv, index);
        index++;
        break;
      case '--fhir-table-runtime-root':
        options.fhirTableRuntimeRoot = optionValue(argv, index);
        index++;
        break;
      case '--fhir-defs-root':
        options.fhirDefsRoot = optionValue(argv, index);
        index++;
        break;
      case '--fhir-spec-root':
        options.fhirSpecRoot = optionValue(argv, index);
        index++;
        break;
      case '--replace':
        options.replace = true;
        break;
      case '--help':
      case '-h':
        options.help = true;
        break;
      default:
        throw new Error(`Unknown option: ${argument}`);
    }
  }

  if (!options.help) {
    options.xverSource = {
      ...readCrossVersionSource(
        path.join(PROJECT_ROOT, 'data/fhir-cross-version/source.json'),
      ),
      ...options.xverSource,
    };
  }

  return options;
}

/**
 * Run the maintainer CLI.
 *
 * @param {string[]} argv CLI arguments after the script name.
 * @returns {Promise<number>} Process exit code.
 */
export async function main(argv) {
  let options;
  try {
    options = parseArgs(argv);
    if (options.help) {
      printUsage();
      return 0;
    }
    if (options.output && options.checkRoot) {
      throw new Error('--output and --check-root cannot be used together');
    }
    if (!options.output && !options.checkRoot) {
      throw new Error('--output or --check-root is required');
    }

    if (options.checkRoot) {
      const result = await checkRuntimeDataFreshness({
        ...options,
        runtimeDataRoot: options.checkRoot,
      });
      console.error(
        `Runtime mappings are fresh and the runtime root is valid: ` +
        `${path.resolve(options.checkRoot)} ` +
        `(${result.filesCompared} indexed files)`,
      );

      return 0;
    }

    const manifest = await generateRuntimeData(options);
    console.error(
      `Generated ${manifest.artifacts.length} runtime artifacts in ${path.resolve(options.output)}`,
    );
    if (options.reviewOutput) {
      console.error(`Wrote canonical review JSON to ${path.resolve(options.reviewOutput)}`);
    }

    return 0;
  } catch (error) {
    console.error(`Error: ${error.message}`);
    return 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2));
}
